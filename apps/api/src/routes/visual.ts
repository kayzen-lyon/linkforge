export interface VisualRouteOptions {
  readonly ogService: OgService;
  readonly paletteService: PaletteService;
  readonly animationService: AnimationService;
}

/** `/og`, `/palette` and `/animation`. */
export const visualRoutes: FastifyPluginAsyncTypebox<VisualRouteOptions> = async (app, options) => {
  app.get('/og', { schema: { querystring: OgQuery } }, async (request, reply) => {
    const { title, template = 'classic', theme = 'light', format = 'png', force = false, ttl } = request.query;
    if (title.trim() === '') throw AppError.invalidParams('title: must not be blank');
    const accent = parseHexColor(request.query.accent ?? '2563eb', 'accent');
    const result = await options.ogService.render({
      title: title.trim(),
      description: request.query.description?.trim() || null,
      site: request.query.site?.trim() || null,
      author: request.query.author?.trim() || null,
      label: request.query.label?.trim() || null,
      template,
      theme,
      // Opaque on purpose: the accent is a background in two templates.
      accent: accent.css.slice(0, 7),
      format,
      force,
      ttlSeconds: ttl ?? null,
    });
    return reply
      .header('content-type', result.contentType)
      .header('x-cache', result.cached ? 'HIT' : 'MISS')
      .header('x-render-source', 'browser')
      .header('cache-control', cacheControl(result.ttlSeconds))
      .send(result.image);
  });

  app.get('/palette', { schema: { querystring: PaletteQuery } }, async (request, reply) => {
    const startedAt = performance.now();
    const { url, count = 5, force = false, ttl } = request.query;
    const result = await options.paletteService.palette({ url, count, force, ttlSeconds: ttl ?? null });
    return sendEnvelope(request, reply, result, startedAt);
  });

  app.get('/animation', { schema: { querystring: AnimationQuery } }, async (request, reply) => {
    const { url, width = 800, height = 500, frames = 6, delay = 800, force = false, ttl } = request.query;
    const result = await options.animationService.capture({
      url,
      width,
      height,
      frames,
      delayMs: delay,
      hideBanners: request.query.hideBanners ?? true,
      blockAds: request.query.blockAds ?? false,
      headers: targetHeadersOf(request.query),
      force,
      ttlSeconds: ttl ?? null,
    });
    return reply
      .header('content-type', 'image/apng')
      .header('x-animation-frames', String(result.frames))
      .header('x-cache', result.cached ? 'HIT' : 'MISS')
      .header('x-render-source', 'browser')
      .header('cache-control', cacheControl(result.ttlSeconds))
      .send(result.image);
  });
};
