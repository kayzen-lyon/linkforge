const Nullable = <T extends TSchema>(schema: T) => Type.Union([schema, Type.Null()]);
const Binary = Type.String({ format: 'binary' });
const Text = (max: number, description: string) => Type.String({ minLength: 1, maxLength: max, description });

// --- /og ----------------------------------------------------------------------

const OgQuery = Type.Object(
  {
    title: Text(OG_LIMITS.title, 'Headline of the card. Plain text: markup is shown as text, never interpreted.'),
    description: Type.Optional(Text(OG_LIMITS.description, 'Supporting line under the title (two lines at most are shown).')),
    site: Type.Optional(Text(OG_LIMITS.site, 'Site or brand name, bottom left.')),
    author: Type.Optional(Text(OG_LIMITS.author, 'Author or date, bottom right.')),
    label: Type.Optional(Text(OG_LIMITS.label, 'Small pill above the title (`Guide`, `New`).')),
    template: Type.Optional(
      Type.Enum([...OG_TEMPLATES], {
        type: 'string',
        default: 'classic',
        description: '`classic`: plain card with an accent rule. `gradient`: accent gradient background. `split`: accent band on the left.',
      }),
    ),
    theme: Type.Optional(Type.Enum(['light', 'dark'], { type: 'string', default: 'light' })),
    accent: Type.Optional(
      Type.String({ pattern: HEX_COLOR_PATTERN, default: '2563eb', description: 'Accent colour: hexadecimal `RGB` or `RRGGBB`, with or without `#`.' }),
    ),
    format: Type.Optional(Type.Enum(['png', 'jpeg'], { type: 'string', default: 'png' })),
    force: ForceParam,
    ttl: TtlParam,
  },
  { additionalProperties: false },
);

