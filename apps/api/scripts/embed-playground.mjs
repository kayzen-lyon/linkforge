/**
 * Embeds the built website (apps/web/dist) into the API source so that a
 * single serverless function can serve it, without relying on the platform to
 * ship extra files next to the bundle.
 *
 * Every servable file of the build is embedded with its content type. HTML
 * pages are later exposed at their clean URL as well (`/docs.html` → `/docs`,
 * `/en/index.html` → `/en/`): see `src/routes/playground.ts`.
 *
 * Usage: node scripts/embed-playground.mjs   (run from apps/api, after the web build)
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const webDist = fileURLToPath(new URL('../../web/dist/', import.meta.url));
const target = fileURLToPath(new URL('../src/generated/playground-assets.ts', import.meta.url));

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};

const assets = [];
let bytes = 0;
// Dot-directories matter here: `.well-known/security.txt` is part of the site.
for (const entry of (await readdir(webDist, { recursive: true })).sort()) {
  const contentType = CONTENT_TYPES[extname(entry).toLowerCase()];
  if (contentType === undefined) continue;
  const content = await readFile(join(webDist, entry));
  bytes += content.length;
  assets.push({
    path: `/${entry.split(sep).join('/')}`,
    contentType,
    base64: content.toString('base64'),
  });
}

if (!assets.some((asset) => asset.path === '/index.html')) {
  throw new Error(`No index.html found in ${webDist}: build apps/web first`);
}

const source = `// Generated by scripts/embed-playground.mjs. Do not edit.
export interface EmbeddedAsset {
  readonly path: string;
  readonly contentType: string;
  readonly base64: string;
}

export const PLAYGROUND_ASSETS: readonly EmbeddedAsset[] = ${JSON.stringify(assets, null, 2)};
`;

await writeFile(target, source);
const pages = assets.filter((asset) => asset.path.endsWith('.html')).length;
console.log(`Embedded ${assets.length} file(s), ${pages} page(s), ${Math.round(bytes / 1024)} KiB`);

// Where the weight is, by kind of file.
const byKind = new Map();
for (const asset of assets) {
  const kind = extname(asset.path).slice(1);
  byKind.set(kind, (byKind.get(kind) ?? 0) + Math.floor((asset.base64.length * 3) / 4));
}
console.log(
  [...byKind]
    .sort((a, b) => b[1] - a[1])
    .map(([kind, size]) => `${kind} ${Math.round(size / 1024)} KiB`)
    .join(' · '),
);
